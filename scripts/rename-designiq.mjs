#!/usr/bin/env node
/**
 * The mechanical half of the bpm-iq → design-iq rename (Release B), as a
 * re-runnable codemod: run it on any branch that predates the rename and it
 * rewrites the same tokens the rename PR rewrote, so an open branch rebases
 * onto the renamed main with no hand-merging of import lines.
 *
 *   node scripts/rename-designiq.mjs           # rewrite tracked files in place
 *   node scripts/rename-designiq.mjs --check   # list what would change, exit 1 if anything would
 *
 * Only tokens with exactly ONE meaning are rewritten here (the npm scope,
 * compound names like bpmiq-live-host, the widget boot marker, the session
 * cookies …). A bare "bpmiq" is an identifier in one place and the display name
 * in the next, so it is left to humans — as are the contract file name, which
 * stays readable under its legacy name, and everything frozen below.
 *
 * FROZEN — never rewritten, because they are stored in customer files, customer
 * issue trackers or the .git of running installations (see the pinning tests):
 * the sticky XML namespace and its `bpmiq:` prefix, the todo anchor marker, the
 * `bpmiq/moved` room message, the host-state file names, the DMN namespace
 * base. Lines carrying the marker `legacy-name-ok` are skipped as a whole.
 * CHANGELOG.md and the ADRs written before the rename are history and skipped.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const CHECK = process.argv.includes("--check");

/** files that are history or generated — never rewritten */
const SKIP_FILE = [
  /^CHANGELOG\.md$/,
  /^docs\/adr\/000[1-7]-/,
  /^pnpm-lock\.yaml$/, // regenerated by `pnpm install` after the manifests change
  /^scripts\/rename-designiq\.mjs$/,
];

/** tokens masked before the rules run and restored after (legacy-name-ok) */
const FROZEN = [
  /https?:\\?\/\\?\/bpmiq\\?\.io\\?\/schema(?:\\?\/[\w.\\]*)*/g, // sticky namespace URI, plain or regex-escaped
  /bpmiq\\?\.dev/g, // DMN namespace base of existing decisions
  /xmlns:bpmiq/g,
  /\bbpmiq:(?:sticky|Sticky|mode|todo|\*)/g,
  /\bbpmiq\/moved\b/g,
  /\bbpmiq-(?:conflicts|released|renames)\.json|\bbpmiq-parked\b/g,
  /\bbpmiq\.yml\b/g, // the contract file stays readable under its legacy name
  /\bbpm-iq-cloud\b/g, // a different (private) repository
  /\bvendor\/bpmiq\b|\bbump-bpmiq\b/g, // that repository's own paths
];

/** the rewrite rules, applied in order to every unmasked line */
const RULES = [
  [/@bpmiq(?=\\?\/)/g, "@designiq"], // the npm scope — import specifiers, manifests, escaped regexes
  [/miragon%2Fbpmiq--live--host/g, "miragon%2Fdesigniq--live--host"], // shields.io badge escaping
  [/\bbpmiq-live-host\b/g, "designiq-live-host"], // the container image
  [/\bbpmiq-mcp\b/g, "designiq-mcp"], // image tag, Keycloak client id, User-Agent
  [/\bbpmiq-validate\b/g, "designiq-validate"], // the validator's bin
  [/\bbpmiq-web\b/g, "designiq-web"], // Keycloak client id
  [/\bbpmiq-data\b/g, "designiq-data"], // the documented Docker volume
  [/\brealm-bpmiq\.json\b/g, "realm-designiq.json"],
  [/\brealms\/bpmiq\b/g, "realms/designiq"],
  [/__BPMIQ_BOOT__/g, "__DESIGNIQ_BOOT__"], // widget boot marker
  [/\bBPMIQ_BOOT\b/g, "DESIGNIQ_BOOT"],
  [/\bbpm_live_(sid|oauth|pkce|editor)\b/g, "designiq_$1"], // session + login-flow cookies
  [/\bmiragon-gmbh(\\?\.)bpm-live\b/g, "miragon-gmbh$1design-iq"], // VS Code extension id, plain or regex-escaped
  [/\bbpmLive\b/g, "designiq"], // VS Code command / setting / secret prefix
  [/\bbpm-live-host\b/g, "designiq-live-host"], // User-Agent
  [/\bbpm-live-create-app\b/g, "designiq-create-app"], // User-Agent
  [/\bbpmiq-live\b/g, "designiq-live"], // Live Host MCP serverInfo name (after the -live-host rule)
  [/\bonFileSystem:bpm-live\b/g, "onFileSystem:designiq"], // VS Code activation event
  [/\bbpm-live:/g, "designiq:"], // VS Code document URI scheme
  [/\bbpm-(todo-badge|diff-(?:viewer|added|removed|changed|layout)|presence|connect-repo)\b/g, "designiq-$1"], // CSS classes + custom properties
  [/\bbpmRemoteCarets\b/g, "designiqRemoteCarets"], // data attribute
  [/\bx-bpmiq-model\b/g, "x-designiq-model"], // drag-and-drop media type
  [/ui:\/\/bpmiq\//g, "ui://designiq/"], // MCP-App resource URIs
  [/\bbpmiq-modeler\b/g, "designiq-modeler"], // MCP-App client name (the claim channel is frozen, legacy-name-ok)
  [/\bbpmiq-(sticky|palette)/g, "designiq-$1"], // CSS classes + palette entry ids
  [/\bbpmiq\.(repos|returnTo)\b/g, "designiq.$1"], // browser storage keys
  [/\bMiragon\/bpm-iq\b/g, "Miragon/design-iq"], // the GitHub repository
  [/\bbpm-iq\b/g, "design-iq"], // the repository slug elsewhere (paths, commit messages)
];

const files = execFileSync("git", ["ls-files", "-z"], { encoding: "utf8" })
  .split("\0")
  .filter((f) => f && !SKIP_FILE.some((re) => re.test(f)));

let changedFiles = 0;
let changedLines = 0;
for (const file of files) {
  let text;
  try {
    text = readFileSync(file, "utf8");
  } catch {
    continue; // a deleted-but-staged path, a submodule
  }
  if (text.includes("\0")) continue; // binary

  let touched = 0;
  const out = text.split("\n").map((line) => {
    if (line.includes("legacy-name-ok")) return line;
    const masked = [];
    let work = line;
    for (const re of FROZEN) {
      work = work.replace(re, (m) => {
        masked.push(m);
        return `\u0000${masked.length - 1}\u0000`;
      });
    }
    for (const [re, to] of RULES) work = work.replace(re, to);
    work = work.replace(/\u0000(\d+)\u0000/g, (_, i) => masked[Number(i)]);
    if (work !== line) touched++;
    return work;
  });

  if (touched === 0) continue;
  changedFiles++;
  changedLines += touched;
  if (CHECK) console.log(`${file}: ${touched} line(s)`);
  else writeFileSync(file, out.join("\n"));
}

console.log(`${CHECK ? "would rewrite" : "rewrote"} ${changedLines} line(s) in ${changedFiles} file(s)`);
if (CHECK && changedFiles > 0) process.exit(1);
